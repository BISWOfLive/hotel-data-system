"""★ 共享能力层 ``push/`` —— 段2 的「推出去」地基(段2 §5.1)。

为什么单独一层(而不是塞进 ``domains/report``)
==============================================

旧系统 ``app/pusher.py`` 647 行**什么都插一手**:直接读表、直接调采集器、
直接算轮换、直接组装日报 —— 这是它变成"上帝模块"的根因(段2 §1.3)。

新架构把"推送"拆成**四件互不依赖的事**,各自一个模块:

=========================  ==========================================================
模块                        只做什么
=========================  ==========================================================
``bindings``               群 ↔ 酒店绑定读写(过滤 ``paused``,一群多店分组)
``sender``                 ★ 发送原语:文本拆分 + 图片逐张 + 素材上传调用
``dispatcher``             ★ 限频 + 重试 + 异步队列(**不关心内容从哪来**)
``audit``                  ``push_logs`` 写入与查询(去重依据 + 成功率口径)
``service``                ★ 对段3 的推送契约(**段3 复用**,含 ``send_alert``)
=========================  ==========================================================

**依赖方向**:``domains/*`` 可以 import ``push/*``;``push/*`` **不 import 任何 domain**
(需要域内能力时用 ``Runtime`` 注入回调)。这样段3 的比价域可以直接复用本层,
而不会把报告引擎拖进来。

**告警的落点**:普通推送写 ``push_logs``;预警写 ``alert_logs``(A2-8 语义分离)。
两边的"成功率"口径不同,混表会让两边都算不清 —— 见 :mod:`hoteldata.infra.models.alert`。
"""

